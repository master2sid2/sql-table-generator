func TestImportSnippets(t *testing.T) {
	tests := []struct {
		name, src string
		headers   []string
		rows      [][]string
	}{
		{"insert only", "INSERT INTO t (a, b) VALUES (1, 'x'), (2, NULL);",
			[]string{"a", "b"}, [][]string{{"1", "x"}, {"2", "NULL"}}},
		{"insert without columns", "insert into t values (1,'a',now());",
			[]string{"col1", "col2", "col3"}, [][]string{{"1", "a", "now()"}}},
		{"no semicolons", "INSERT INTO t (a) VALUES (1)\nINSERT INTO t (a) VALUES (2)",
			[]string{"a"}, [][]string{{"1"}, {"2"}}},
		{"sqlite or replace", "INSERT OR REPLACE INTO t (a) VALUES (-1.5)",
			[]string{"a"}, [][]string{{"-1.5"}}},
		{"phpmyadmin alter", "CREATE TABLE `t` (`id` int(11) NOT NULL, `n` text);\nALTER TABLE `t` ADD PRIMARY KEY (`id`);\n" +
			"ALTER TABLE `t` MODIFY `id` int(11) NOT NULL AUTO_INCREMENT, AUTO_INCREMENT=5;",
			[]string{"id", "n"}, [][]string{}},
		{"copy without columns", "COPY t FROM stdin;\n1\tx\n\\.\n", []string{"col1", "col2"}, [][]string{{"1", "x"}}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			imp, err := Import(tt.src)
			if err != nil {
				t.Fatal(err)
			}
			if !reflect.DeepEqual(imp.Headers, tt.headers) || !reflect.DeepEqual(imp.Rows, tt.rows) {
				t.Errorf("headers %q rows %q", imp.Headers, imp.Rows)
			}
			// MODIFY redefines the column; the key comes from ADD PRIMARY KEY before it.
			if want := (Column{Type: TypeInt, NotNull: true, AutoIncrement: true, PrimaryKey: true}); tt.name == "phpmyadmin alter" && imp.Columns[0] != want {
				t.Errorf("id column %+v, want %+v", imp.Columns[0], want)
			}
		})
	}
	if _, err := Import("SELECT 1;"); !errors.Is(err, ErrNoTable) {
		t.Errorf("err = %v, want ErrNoTable", err)
	}
}

func TestLooksLikeSQL(t *testing.T) {
	yes := []string{
		"CREATE TABLE t (a int)",
		"-- comment\n/* block */;\ninsert into t values (1)",
		"INSERT [dbo].[t] ([a]) VALUES (1)",
		"create temporary table if not exists t (a int)",
	}
	no := []string{"id,name\n1,Alice", "set the table", "+----+\n| id |\n+----+", "create a table please"}
	for _, s := range yes {
		if !LooksLikeSQL(s) {
			t.Errorf("LooksLikeSQL(%q) = false", s)
		}
	}
	for _, s := range no {
		if LooksLikeSQL(s) {
			t.Errorf("LooksLikeSQL(%q) = true", s)
		}
	}
}

func TestStructureAndDescribe(t *testing.T) {
	h, rows, cols := sample()
	p := Prepare(h, rows, cols)
	Generate(p, Options{Dialect: MySQL, Create: true})
	text := table.Render(Structure(p, MySQL), table.Options{Align: table.AlignLeft})
	want := "+--------+---------------+------+-----+---------+----------------+---------+\n" +
		"| Field  | Type          | Null | Key | Default | Extra          | Comment |\n" +
		"+--------+---------------+------+-----+---------+----------------+---------+\n" +
		"| id     | INT           | NO   | PRI | NULL    | auto_increment |         |\n" +
		"| name   | VARCHAR(16)   | NO   |     | NULL    |                | who     |\n" +
		"| price  | DECIMAL(10,2) | YES  |     | 0       |                |         |\n" +
		"| active | BOOLEAN       | YES  |     | yes     |                |         |\n" +
		"| order  | INT           | YES  |     | NULL    |                |         |\n" +
		"+--------+---------------+------+-----+---------+----------------+---------+\n"
	if text != want {
		t.Errorf("got:\n%s\nwant:\n%s", text, want)
	}

	// and back
	parsed, err := table.ParseText(text, table.FormatAuto, true)
	if err != nil {
		t.Fatal(err)
	}
	names, got, ok := FromDescribe(parsed.Table, text)
	if !ok || !reflect.DeepEqual(names, h) {
		t.Fatalf("FromDescribe: %v %q", ok, names)
	}
	wantCols := []Column{
		{Type: TypeInt, NotNull: true, PrimaryKey: true, AutoIncrement: true},
		{Type: TypeVarchar, Length: 16, NotNull: true, Comment: "who"},
		{Type: TypeDecimal, Length: 10, Scale: 2, Default: "0"},
		{Type: TypeBool, Default: "yes"},
		{Type: TypeInt},
	}
	if !reflect.DeepEqual(got, wantCols) {
		t.Errorf("columns:\n got %+v\nwant %+v", got, wantCols)
	}
}

