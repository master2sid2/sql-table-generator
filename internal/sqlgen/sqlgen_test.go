func TestGenerate(t *testing.T) {
	want := map[string]string{
		MySQL: "CREATE TABLE shop.items (\n" +
			"  id      INT           NOT NULL AUTO_INCREMENT PRIMARY KEY,\n" +
			"  name    VARCHAR(16)   NOT NULL COMMENT 'who',\n" +
			"  price   DECIMAL(10,2) DEFAULT 0,\n" +
			"  active  BOOLEAN       DEFAULT TRUE,\n" +
			"  `order` INT\n" +
			") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;\n\n" +
			"INSERT INTO shop.items (id, name, price, active, `order`) VALUES\n" +
			"  (1, 'O''Hara', 10.50, TRUE, NULL),\n" +
			"  (2, 'back\\\\slash', NULL, FALSE, 3);\n",
		Postgres: "CREATE TABLE shop.items (\n" +
			"  id      INTEGER       NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n" +
			"  name    VARCHAR(16)   NOT NULL,\n" +
			"  price   NUMERIC(10,2) DEFAULT 0,\n" +
			"  active  BOOLEAN       DEFAULT TRUE,\n" +
			"  \"order\" INTEGER\n" +
			");\n\n" +
			"COMMENT ON COLUMN shop.items.name IS 'who';\n\n" +
			"INSERT INTO shop.items (id, name, price, active, \"order\") VALUES\n" +
			"  (1, 'O''Hara', 10.50, TRUE, NULL),\n" +
			"  (2, 'back\\slash', NULL, FALSE, 3);\n\n" +
			"SELECT setval(pg_get_serial_sequence('shop.items', 'id'), (SELECT MAX(id) FROM shop.items));\n",
		SQLite: "CREATE TABLE shop.items (\n" +
			"  id      INTEGER       NOT NULL PRIMARY KEY AUTOINCREMENT,\n" +
			"  name    VARCHAR(16)   NOT NULL,  -- who\n" +
			"  price   DECIMAL(10,2) DEFAULT 0,\n" +
			"  active  BOOLEAN       DEFAULT 1,\n" +
			"  \"order\" INTEGER\n" +
			");\n\n" +
			"INSERT INTO shop.items (id, name, price, active, \"order\") VALUES\n" +
			"  (1, 'O''Hara', 10.50, 1, NULL),\n" +
			"  (2, 'back\\slash', NULL, 0, 3);\n",
		MSSQL: "CREATE TABLE shop.items (\n" +
			"  id      INT           NOT NULL IDENTITY(1,1) PRIMARY KEY,\n" +
			"  name    NVARCHAR(16)  NOT NULL,  -- who\n" +
			"  price   DECIMAL(10,2) DEFAULT 0,\n" +
			"  active  BIT           DEFAULT 1,\n" +
			"  [order] INT\n" +
			");\n\n" +
			"SET IDENTITY_INSERT shop.items ON;\n\n" +
			"INSERT INTO shop.items (id, name, price, active, [order]) VALUES\n" +
			"  (1, N'O''Hara', 10.50, 1, NULL),\n" +
			"  (2, N'back\\slash', NULL, 0, 3);\n\n" +
			"SET IDENTITY_INSERT shop.items OFF;\n",
	}
	for d, w := range want {
		t.Run(d, func(t *testing.T) {
			h, rows, cols := sample()
			got, warnings := Generate(Prepare(h, rows, cols), Options{Dialect: d, Table: "shop.items", Create: true, Insert: true, EmptyAsNull: true})
			if got != w {
				t.Errorf("got:\n%s\nwant:\n%s", got, w)
			}
			if len(warnings) > 0 {
				t.Errorf("warnings: %q", warnings)
			}
		})
	}
}

