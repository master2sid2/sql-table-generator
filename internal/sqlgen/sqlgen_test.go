func TestGenerateEdgeCases(t *testing.T) {
	t.Run("empty text is '' unless emptyAsNull", func(t *testing.T) {
		p := Prepare([]string{"a", "n"}, [][]string{{"", "1"}, {"x", ""}}, nil)
		got, _ := Generate(p, Options{Dialect: MySQL, Insert: true})
		if !strings.Contains(got, "('', 1)") || !strings.Contains(got, "('x', NULL)") {
			t.Errorf("got %s", got)
		}
	})
	t.Run("auto increment without values is left out", func(t *testing.T) {
		p := Prepare([]string{"id", "n"}, [][]string{{"", "a"}}, []Column{{PrimaryKey: true, AutoIncrement: true}})
		got, _ := Generate(p, Options{Dialect: MSSQL, Insert: true})
		if got != "INSERT INTO my_table (n) VALUES\n  (N'a');\n" {
			t.Errorf("got %q", got)
		}
	})
	t.Run("composite key", func(t *testing.T) {
		p := Prepare([]string{"a", "b"}, [][]string{{"1", "2"}}, []Column{{PrimaryKey: true}, {PrimaryKey: true}})
		got, _ := Generate(p, Options{Dialect: SQLite, Create: true})
		if !strings.Contains(got, "  b INTEGER NOT NULL,\n  PRIMARY KEY (a, b)\n)") {
			t.Errorf("got %s", got)
		}
	})
	t.Run("sqlite autoincrement needs the single primary key", func(t *testing.T) {
		p := Prepare([]string{"a"}, [][]string{{"1"}}, []Column{{AutoIncrement: true, Unique: true}})
		got, warnings := Generate(p, Options{Dialect: SQLite, Create: true})
		if strings.Contains(got, "AUTOINCREMENT") || len(warnings) != 1 {
			t.Errorf("got %s, warnings %q", got, warnings)
		}
	})
	t.Run("unnamed and empty columns", func(t *testing.T) {
		p := Prepare([]string{"a", "", ""}, [][]string{{"1", "x", ""}}, nil)
		got, _ := Generate(p, Options{Dialect: MySQL, Create: true})
		if !strings.Contains(got, "col2 VARCHAR(16)\n)") || len(p.Warnings) != 1 || !p.Columns[2].Skip {
			t.Errorf("got %s, warnings %q", got, p.Warnings)
		}
	})
	t.Run("defaults", func(t *testing.T) {
		p := Prepare([]string{"a", "b", "c", "d", "e", "f"}, nil, []Column{
			{Type: TypeDate, Default: "CURRENT_DATE"}, {Type: TypeVarchar, Default: "it's"},
			{Type: TypeVarchar, Default: "'quoted'"}, {Type: TypeInt, Default: "abs(-1)"}, {Type: TypeDateTime, Default: "now()"},
			{Type: TypeVarchar, Default: "Unknown (none)"},
		})
		got, _ := Generate(p, Options{Dialect: MySQL, Create: true})
		for _, w := range []string{"DEFAULT (CURRENT_DATE)", "DEFAULT 'it''s'", "DEFAULT 'quoted'", "DEFAULT (abs(-1))", "DEFAULT CURRENT_TIMESTAMP",
			"DEFAULT 'Unknown (none)'"} {
			if !strings.Contains(got, w) {
				t.Errorf("no %q in\n%s", w, got)
			}
		}
	})
	t.Run("many rows are split into batches", func(t *testing.T) {
		rows := make([][]string, 2500)
		for i := range rows {
			rows[i] = []string{"1"}
		}
		got, _ := Generate(Prepare([]string{"a"}, rows, nil), Options{Dialect: MSSQL, Insert: true})
		if n := strings.Count(got, "INSERT INTO"); n != 3 {
			t.Errorf("%d INSERT statements, want 3", n)
		}
	})
	t.Run("no columns", func(t *testing.T) {
		if got, _ := Generate(Prepare([]string{""}, [][]string{{""}}, nil), Options{Create: true}); got != "" {
			t.Errorf("got %q", got)
		}
	})
}

// TestRoundTrip generates SQL for every dialect and reads it back.
func TestRoundTrip(t *testing.T) {
	headers := []string{"id", "name", "note", "price", "flag", "born", "seen", "uid", "Mixed Case"}
	rows := [][]string{
		{"1", "O'Brien", "line\nbreak and \\ backslash", "3.50", "true", "2001-02-03", "2024-01-02 03:04:05", "5f2b1c3e-1111-4a2b-9c3d-000000000001", "Юлия 漢字"},
		{"2", "Ann", "NULL", "-10.25", "false", "NULL", "NULL", "NULL", "x"},
	}
	cols := []Column{
		{PrimaryKey: true, AutoIncrement: true},
		{Type: TypeVarchar, Length: 50, NotNull: true, Default: "nobody"},
		{Type: TypeText, Comment: "free text"},
		{Type: TypeDecimal, Length: 12, Scale: 2, Default: "0"},
		{Default: "true"},
		{},
		{Default: "CURRENT_TIMESTAMP"},
		{Unique: true},
		{},
	}
	for _, d := range []string{MySQL, Postgres, SQLite, MSSQL} {
		t.Run(d, func(t *testing.T) {
			p := Prepare(headers, rows, cols)
			sql, _ := Generate(p, Options{Dialect: d, Table: "people", Create: true, Insert: true})
			imp, err := Import(sql)
			if err != nil {
				t.Fatal(err)
			}
			if imp.Table != "people" || !reflect.DeepEqual(imp.Headers, headers) {
				t.Fatalf("table %q headers %q", imp.Table, imp.Headers)
			}
			if imp.Dialect != d {
				t.Errorf("dialect detected as %q", imp.Dialect)
			}
			for i, e := range p.Columns {
				got := imp.Columns[i]
				want := e.Column
				if d == SQLite || d == MSSQL {
					want.Comment = "" // written as -- comments
				}
				if d == SQLite && isInteger(want.Type) {
					want.Type = TypeInt // SQLite has one INTEGER
				}
				switch {
				case want.Type == TypeUUID && d == MySQL:
					want.Type, want.Length = TypeChar, 36 // CHAR(36)
				case want.Type == TypeUUID && d == SQLite:
					want.Type = TypeText
				}
				if want.Type == TypeBool {
					gb, _ := parseBool(got.Default)
					wb, _ := parseBool(want.Default)
					got.Default, want.Default = "", ""
					if gb != wb {
						t.Errorf("%s: default %v, want %v", e.Name, gb, wb)
					}
				}
				want.NotNull = want.NotNull || want.PrimaryKey || want.AutoIncrement
				if !isText(want.Type) && want.Type != TypeDecimal || want.Type == TypeUUID || want.Type == TypeText {
					want.Length, want.Scale = 0, 0
				}
				if got != want {
					t.Errorf("%s:\n got %+v\nwant %+v", e.Name, got, want)
				}
			}
			for r, row := range rows {
				for c, v := range row {
					g := imp.Rows[r][c]
					if headers[c] == "flag" {
						gb, _ := parseBool(g)
						wb, _ := parseBool(v)
						if gb == wb {
							continue
						}
					}
					if g != v {
						t.Errorf("row %d %s: got %q, want %q", r, headers[c], g, v)
					}
				}
			}
		})
	}
}

