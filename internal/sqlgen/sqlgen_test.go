func TestInfer(t *testing.T) {
	tests := []struct {
		name   string
		values []string
		want   inferred
	}{
		{"empty", []string{"", "NULL"}, inferred{typ: TypeVarchar, length: 255}},
		{"int", []string{"1", "-20", "", "300"}, inferred{typ: TypeInt, maxLen: 3}},
		{"bigint", []string{"1", "9000000000"}, inferred{typ: TypeBigInt, maxLen: 10}},
		{"leading zero is text", []string{"007", "12"}, inferred{typ: TypeVarchar, length: 16, maxLen: 3}},
		{"decimal", []string{"10.5", "3", "-0.25"}, inferred{typ: TypeDecimal, length: 10, scale: 2, maxLen: 5}},
		{"wide decimal", []string{"123456789012.125"}, inferred{typ: TypeDecimal, length: 15, scale: 3, maxLen: 16}},
		{"float", []string{"1e10", "2.5"}, inferred{typ: TypeFloat, maxLen: 4}},
		{"bool", []string{"true", "FALSE"}, inferred{typ: TypeBool, maxLen: 5}},
		{"date", []string{"2024-01-02"}, inferred{typ: TypeDate, maxLen: 10}},
		{"datetime", []string{"2024-01-02", "2024-01-02T10:00:00Z"}, inferred{typ: TypeDateTime, maxLen: 20}},
		{"time", []string{"10:00", "23:59:59"}, inferred{typ: TypeTime, maxLen: 8}},
		{"uuid", []string{"5f2b1c3e-1111-4a2b-9c3d-000000000001"}, inferred{typ: TypeUUID, maxLen: 36}},
		{"json", []string{`{"a":1}`, `[1,2]`}, inferred{typ: TypeJSON, maxLen: 7}},
		{"text", []string{strings.Repeat("x", 2000)}, inferred{typ: TypeText, maxLen: 2000}},
		{"varchar counts runes", []string{"Юлия Петрова-Сидорова"}, inferred{typ: TypeVarchar, length: 32, maxLen: 21}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := infer(tt.values); got != tt.want {
				t.Errorf("infer(%q) = %+v, want %+v", tt.values, got, tt.want)
			}
		})
	}
}

